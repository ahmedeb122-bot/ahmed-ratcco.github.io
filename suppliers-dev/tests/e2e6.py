import asyncio
from playwright.async_api import async_playwright
B='http://localhost:8765/'
XLSX=open('/home/claude/work/xlsxpkg/package/dist/xlsx.full.min.js').read()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,accept_downloads=True)
        await ctx.route('**/cdnjs.cloudflare.com/**',lambda r:r.fulfill(status=200,content_type='application/javascript',body=XLSX))
        await ctx.route('**/fonts.googleapis.com/**',lambda r:r.abort())
        pg=await ctx.new_page(); errs=[]
        pg.on('pageerror',lambda e:errs.append('PAGE '+str(e)))
        await pg.add_init_script("window.open=()=>{}")
        await pg.goto(B+'t-index.html'); await pg.wait_for_timeout(1800)
        print('tiles:',(await pg.inner_text('#tiles')).replace('\n',' | '))
        await pg.screenshot(path='/home/claude/work/v3-home.png',full_page=True)
        await pg.click('[data-group=cables]'); await pg.wait_for_timeout(400)
        print('cables:',await pg.inner_text('#count'),'|',(await pg.inner_text('#cat-chips')).replace('\n',' '),'|',(await pg.inner_text('#type-chips')).replace('\n',' '))
        names=await pg.locator('.sc-main b').all_inner_texts(); print('order:',names[:8])
        await pg.click('[data-cat="MV Cables"]'); await pg.wait_for_timeout(300)
        print('mv cables:',await pg.inner_text('#count'), (await pg.locator('.sc-main b').all_inner_texts())[:5])
        await pg.click('[data-ftype=Manufacturer]'); await pg.wait_for_timeout(300)
        print('mfr only:',await pg.inner_text('#count'))
        await pg.screenshot(path='/home/claude/work/v3-list.png')
        await pg.click('.nav [data-go=home]'); await pg.wait_for_timeout(300)
        await pg.click('[data-mode=con]'); await pg.wait_for_timeout(300)
        print('con tiles:',(await pg.inner_text('#tiles')).replace('\n',' | '))
        await pg.click('[data-mode=sup]')
        # add form
        await pg.click('.nav .plus'); await pg.wait_for_timeout(300)
        await pg.fill('#a-name','Al Khuraiji Test Showroom'); await pg.fill('#a-mob','0561112222')
        await pg.click('[data-general]'); await pg.wait_for_timeout(200)
        print('after general:',await pg.inner_text('#cat-count'), await pg.locator('.secb[aria-pressed=true]').count())
        await pg.click('[data-sec=lighting]'); await pg.click('#fine summary'); await pg.wait_for_timeout(200)
        await pg.click('#fine [data-pick="Outdoor Lighting & Poles"]'); await pg.wait_for_timeout(200)
        print('fine open still:', await pg.locator('#fine[open]').count())
        await pg.fill('#a-other','لوحات إعلانية'); await pg.click('[data-acity=Riyadh]')
        await pg.screenshot(path='/home/claude/work/v3-add.png',full_page=True)
        await pg.fill('#a-by','Tester')
        await pg.click('#f-add [type=submit]'); await pg.wait_for_timeout(900)
        print('submit:',await pg.inner_text('#a-msg'))
        # contractor
        await pg.fill('#a-name','Test MEP Contractor'); await pg.fill('#a-mob','0563334444')
        await pg.click('#a-type [data-v=Contractor]'); await pg.wait_for_timeout(200)
        print('con picker:',(await pg.inner_text('#cat-picker')).replace('\n',' ')[:200])
        await pg.click('[data-pick="MEP Contracting"]')
        await pg.click('#f-add [type=submit]'); await pg.wait_for_timeout(900)
        print('submit con:',await pg.inner_text('#a-msg'))
        # paste
        await pg.click('#b-paste')
        await pg.fill('#paste-text','شركة الضوء للكابلات\nمورد كابلات جهد متوسط وقواطع\n0507654321\nالدمام')
        await pg.click('#paste-go'); await pg.wait_for_timeout(400)
        print('paste cats:',await pg.inner_text('#cat-count'), await pg.locator('.secb[aria-pressed=true] span').all_inner_texts())
        # bulk
        await pg.goto(B+'t-index.html#bulk'); await pg.wait_for_timeout(1200)
        await pg.set_input_files('#bulk-file','/home/claude/work/bulk-test.xlsx'); await pg.wait_for_timeout(1500)
        print('bulk:',(await pg.inner_text('#bulk-sums')).replace('\n',' '),'|',(await pg.inner_text('#bulk-rows')).replace('\n',' / ')[:400])
        async with pg.expect_download() as dl: await pg.click('#bulk-tpl')
        d=await dl.value; await d.save_as('/home/claude/work/tpl.xlsx')
        print('errors',errs); await b.close()
asyncio.run(main())
